/**
 * Service Cari Lowongan (PRD Cari Lowongan §10–§12).
 *
 * Alur satu pencarian:
 *   kuota → profil pencarian (cache per versi CV) → ambil kandidat dari indeks
 *   lokal → skor rule-based (gratis) → SATU call LLM untuk 5 "Wajib Coba"
 *   → simpan run + match.
 *
 * Dua hal yang dijaga ketat di sini:
 * 1. Tidak ada call ke sumber eksternal. Pencarian membaca indeks, titik.
 * 2. Skor di halaman ini adalah "perkiraan cocok" — BUKAN skor analisis. Analisis
 *    penuh tetap memakai kuota analisis lewat alur yang sudah ada.
 */

const MS_PER_DAY = 86_400_000
const MS_PER_HOUR = 3_600_000

const SENIORITY_ORDER = ["entry", "mid", "senior", "lead"] as const
type Seniority = (typeof SENIORITY_ORDER)[number]

type DiscoveredJobRow = Awaited<ReturnType<typeof prisma.discoveredJob.findMany>>[number]

function asStringArray(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((item): item is string => typeof item === "string") : []
}

function hoursSince(date: Date | null | undefined): number | null {
  if (!date) return null
  return Math.max(0, Math.round((Date.now() - date.getTime()) / MS_PER_HOUR))
}

function seniorityFromTitle(title: string): Seniority | null {
  const value = title.toLowerCase()
  if (/\b(head|lead|principal|manager|director|vp)\b/.test(value)) return "lead"
  if (/\b(senior|sr\.?|staff)\b/.test(value)) return "senior"
  if (/\b(junior|jr\.?|intern|magang|entry|fresh)\b/.test(value)) return "entry"
  return null
}

