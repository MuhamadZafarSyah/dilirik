/**
 * Menyiapkan analisis penuh: snippet lowongan dijadikan JobPosting milik user,
 * lalu alur analisis yang SUDAH ADA yang mengerjakan sisanya. Sengaja tidak
 * menduplikasi analysisService — satu mesin analisis untuk seluruh produk.
 *
 * Catatan yang harus jujur ke user: yang tersimpan hanya ringkasan, jadi analisis
 * berbasis snippet bisa kurang lengkap dibanding menempel deskripsi penuh.
 */
export async function prepareMatchAnalysis(
  userId: string,
  matchId: string,
): Promise<{ jobPostingId: string; matchId: string; usedSnippet: boolean }> {
  const match = await loadMatch(userId, matchId)
  if (match.jobPostingId) {
    return { jobPostingId: match.jobPostingId, matchId: match.id, usedSnippet: true }
  }

  const job = match.discoveredJob
  const rawText = [
    `${job.title} — ${job.company}`,
    job.location ? `Lokasi: ${job.location}` : null,
    job.remoteType ? `Tipe kerja: ${job.remoteType}` : null,
    "",
    job.descriptionSnippet,
    "",
    `Sumber: ${job.primarySource}`,
    `Tautan: ${job.applyUrl}`,
  ]
    .filter((line) => line !== null)
    .join("\n")

  const jobPosting = await prisma.jobPosting.create({
    data: {
      userId,
      sourceUrl: job.applyUrl,
      rawText,
      parsedJson: jobParsedFrom(job),
    },
    select: { id: true },
  })

  await prisma.jobMatch.update({
    where: { id: match.id },
    data: { status: "ANALYZED", jobPostingId: jobPosting.id },
  })

  return { jobPostingId: jobPosting.id, matchId: match.id, usedSnippet: true }
}

export async function requestAlert(userId: string, pendingQueryId: string): Promise<void> {
  const pending = await prisma.pendingQuery.findUnique({
    where: { id: pendingQueryId },
    select: { id: true },
  })
  if (!pending) throw new HttpError(404, "NOT_FOUND", "Permintaan pencarian tidak ditemukan")
  await prisma.pendingQuery.update({
    where: { id: pending.id },
    data: { alertRequested: true, userId },
  })
}

export async function getDiscoveryStatus(userId: string): Promise<DiscoveryStatusDto> {
  const [jobCount, indexAgeHours, lastIngestion, entitlement] = await Promise.all([
    prisma.discoveredJob.count({ where: { expiresAt: { gt: new Date() } } }),
    getIndexAgeHours(),
    prisma.ingestionRun.findFirst({
      orderBy: { startedAt: "desc" },
      select: { status: true, providerStatsJson: true },
    }),
    checkDiscoveryEntitlement(userId),
  ])

  const stats = Array.isArray(lastIngestion?.providerStatsJson)
    ? (lastIngestion.providerStatsJson as Array<Record<string, unknown>>)
    : []

  return {
    indexJobCount: jobCount,
    indexAgeHours,
    lastIngestionStatus: lastIngestion?.status ?? null,
    unavailableSources: stats
      .filter((stat) => stat.status === "DISABLED" || stat.status === "ERROR")
      .map((stat) => String(stat.providerId)),
    quota: {
      quota: entitlement.quota,
      used: entitlement.used,
      remaining: entitlement.remaining,
      resetAt: entitlement.resetAt.toISOString(),
    },
  }
}
