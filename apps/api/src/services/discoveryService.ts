export async function listRuns(userId: string): Promise<DiscoveryRunListItemDto[]> {
  const runs = await prisma.jobDiscoveryRun.findMany({
    where: { userId },
    orderBy: { createdAt: "desc" },
    take: 20,
  })
  return runs.map((run) => ({
    id: run.id,
    cvId: run.cvId,
    status: run.status as DiscoveryRunListItemDto["status"],
    candidateCount: run.candidateCount,
    curatedCount: run.curatedCount,
    indexAgeHours: run.indexAgeHours,
    createdAt: run.createdAt.toISOString(),
  }))
}

export async function getRun(userId: string, runId: string) {
  const run = await prisma.jobDiscoveryRun.findFirst({
    where: { id: runId, userId },
    include: {
      matches: { orderBy: { rank: "asc" }, include: { discoveredJob: true } },
      searchProfile: true,
    },
  })
  if (!run) throw new HttpError(404, "NOT_FOUND", "Riwayat pencarian tidak ditemukan")

  const matches = run.matches.map((match) => toJobMatchDto(match, match.discoveredJob))
  return {
    runId: run.id,
    status: run.status,
    createdAt: run.createdAt.toISOString(),
    searchProfile: run.searchProfile ? toProfileDto(run.searchProfile) : null,
    topPicks: matches.filter((match) => match.isTopPick),
    otherCandidates: matches.filter((match) => !match.isTopPick),
    meta: {
      candidateCount: run.candidateCount,
      indexAgeHours: run.indexAgeHours,
      curationNote: run.curationNote,
    },
  }
}

async function loadMatch(userId: string, matchId: string) {
  const match = await prisma.jobMatch.findFirst({
    where: { id: matchId, userId },
    include: { discoveredJob: true },
  })
  if (!match) throw new HttpError(404, "NOT_FOUND", "Lowongan tidak ditemukan")
  return match
}

export async function saveMatch(userId: string, matchId: string): Promise<JobMatchDto> {
  const match = await loadMatch(userId, matchId)
  const updated = await prisma.jobMatch.update({
    where: { id: match.id },
    data: { status: "SAVED" },
  })
  return toJobMatchDto(updated, match.discoveredJob)
}

